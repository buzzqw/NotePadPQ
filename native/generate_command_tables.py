#!/usr/bin/env python3
"""Generate ``native/latex_command_tables.inc`` from ``core/latex_commands``.

The command/environment tables are the single source of truth used by both the
Python lexer and the optional C++ accelerator.  The accelerator cannot import
Python, so rather than repeating the lists in C++ (and keeping them in sync by
hand) they are generated from the Python module here.

Run this after editing ``core/latex_commands.py``::

    python native/generate_command_tables.py

``tests/test_latex_commands.py`` fails when the generated file is stale.
"""

from __future__ import annotations

import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from core import latex_commands  # noqa: E402  (path set above)

_OUT = Path(__file__).resolve().parent / "latex_command_tables.inc"

# C++ table name -> core.latex_commands attribute.
TABLES = (
    ("STRUCTURE_COMMANDS", latex_commands.STRUCTURE_COMMANDS),
    ("REFERENCE_COMMANDS", latex_commands.REFERENCE_COMMANDS),
    ("MATH_ENVIRONMENTS", latex_commands.MATH_ENVIRONMENTS),
    ("VERBATIM_ENVIRONMENTS", latex_commands.VERBATIM_ENVIRONMENTS),
)

_HEADER = (
    "// Generated by native/generate_command_tables.py from\n"
    "// core/latex_commands.py -- do not edit by hand.\n"
)


def render() -> str:
    """Return the full contents of the generated include file."""
    lines: list[str] = [_HEADER]
    for name, values in TABLES:
        lines.append(f"const std::unordered_set<std::string> {name} = {{")
        for value in sorted(values):
            lines.append(f'    "{value}",')
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = _OUT.read_text(encoding="utf-8") if _OUT.is_file() else ""
        if current != text:
            print(f"{_OUT.name} is stale; run native/generate_command_tables.py")
            return 1
        return 0
    _OUT.write_text(text, encoding="utf-8")
    print(f"wrote {_OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
