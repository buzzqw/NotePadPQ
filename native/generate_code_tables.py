"""Generate native/code_lexer_tables.inc from the installed Pygments lexers.

The native code scanner (native/code_native.cpp) replaces Pygments for a few
C-family languages.  To keep the colours users already see, its keyword,
type and builtin tables are derived from Pygments itself: every identifier
found in the Pygments lexer sources is tokenised in a few small contexts and
classified with the same ``_token_to_style`` mapping the Pygments lexer uses.

Unlike the LaTeX tables this is *not* run by setup.py: the output depends on
the installed Pygments version, and builds must be reproducible.  Run it by
hand after a Pygments upgrade and commit the regenerated include:

    python native/generate_code_tables.py
"""

from __future__ import annotations

import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "native" / "code_lexer_tables.inc"

LANGUAGES = ("go", "rust", "kotlin", "swift", "scala", "dart")
# Small snippets in which a candidate word is classified.  The last ones
# catch declaration modifiers (``private val``, ``pub fn``...), which are
# keywords only in front of a declaration.
CONTEXTS = ("a = @ + b\n", "@(x)\n", "x: @\n", "let a: @ = b\n",
            "@ val a = 1\n", "@ fun f() {}\n", "@ fn f() {}\n", "@ func f() {}\n",
            "@ def f = 1\n", "@ class A {}\n")
CLASSES = {"Keyword": "KEYWORDS", "Type": "TYPES", "Builtin": "BUILTINS"}


def _candidates() -> set[str]:
    import pygments.lexers.go
    import pygments.lexers.javascript
    import pygments.lexers.jvm
    import pygments.lexers.objective
    import pygments.lexers.rust

    words: set[str] = set()
    for module in (pygments.lexers.go, pygments.lexers.rust, pygments.lexers.jvm,
                   pygments.lexers.objective, pygments.lexers.javascript):
        words |= {w for w in re.findall(r"[A-Za-z_][A-Za-z0-9_]*",
                                        inspect.getsource(module)) if len(w) > 1}
    return words


def classify() -> dict[str, dict[str, list[str]]]:
    sys.path.insert(0, str(ROOT))
    from pygments.lexers import get_lexer_by_name

    from editor.pygments_lexer import _STYLE_NAMES, _token_to_style

    words = sorted(_candidates())
    tables: dict[str, dict[str, list[str]]] = {}
    for lang in LANGUAGES:
        lexer = get_lexer_by_name(lang)
        found: dict[str, list[str]] = {name: [] for name in CLASSES.values()}
        found["MACROS"] = []
        for word in words:
            # Scala colours every capitalised name as a class: the scanner
            # has a rule for that, the tables would only bloat.
            if lang == "scala" and word[0].isupper():
                continue
            if lang == "rust":
                # Only the macros Pygments knows are coloured as functions;
                # any other ``name!`` stays a plain name plus operator.
                macro = word + "!"
                styles = [_STYLE_NAMES[_token_to_style(ttype)]
                          for _i, ttype, value in
                          lexer.get_tokens_unprocessed(macro + "(x);\n")
                          if value == macro]
                if styles and styles[0] == "Function":
                    found["MACROS"].append(word)
            for context in CONTEXTS:
                styles = [_STYLE_NAMES[_token_to_style(ttype)]
                          for _i, ttype, value in
                          lexer.get_tokens_unprocessed(context.replace("@", word))
                          if value == word]
                if styles and styles[0] != "Default":
                    table = CLASSES.get(styles[0])
                    if table:
                        found[table].append(word)
                    break
        tables[lang] = found
    return tables


def render(tables: dict[str, dict[str, list[str]]]) -> str:
    lines = [
        "// Generated by native/generate_code_tables.py from the installed",
        "// Pygments lexers. Do not edit by hand.",
        "",
    ]
    for lang, found in tables.items():
        for table, words in found.items():
            name = f"{lang.upper()}_{table}"
            lines.append(f"const char *const {name}[] = {{")
            row: list[str] = []
            for word in words:
                row.append(f'"{word}",')
                if sum(len(x) + 1 for x in row) > 70:
                    lines.append("    " + " ".join(row))
                    row = []
            if row:
                lines.append("    " + " ".join(row))
            lines.append("    nullptr,")
            lines.append("};")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    OUTPUT.write_text(render(classify()), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
